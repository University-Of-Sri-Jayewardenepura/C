// hello_world.c
// EN: This program prints "Hello, World!" to the screen.
// SI: මෙය "Hello, World!" තිරයට මුද්‍රණය කරයි.
// TA: இது "Hello, World!" என்பதை திரையில் அச்சிடும்.

#include <stdio.h>

int main(void) {
    // EN: printf shows text on screen.
    // SI: printf භාවිතා කරලේ තිරයේ පෙන්නන්නයි.
    // TA: printf மூலம் திரையில் எழுத்தை காட்டுகிறோம்.
    printf("Hello, World!\n");

    // EN: \n means new line (go to the next line).
    // SI: \n කියන්නෙ නව පේළියක් (ලයින් එකක් යටට).
    // TA: \n என்பது புதிய வரி (அடுத்த வரிக்கு செல்லும்) என்பதாகும்.

    return 0; // EN/SI/TA: Program ends here.
}
